export const CITIES = [...RAW].sort((a, b) => a.localeCompare(b, "he"));

const KNOWN = new Set(CITIES);

export function officialCity(value: string) {
  const name = value.trim().replace(/[-–]/g, " ").replace(/\s+/g, " ");
  if (!name) return "";
  if (KNOWN.has(name)) return name;
  const swapped = name.includes("קריית") ? name.replaceAll("קריית", "קרית") : name.replaceAll("קרית", "קריית");
  if (KNOWN.has(swapped)) return swapped;
  const vav = name.replaceAll("תקוה", "תקווה");
  if (KNOWN.has(vav)) return vav;
  if (name === "תל אביב" || name === "ת״א" || name === 'ת"א') return "תל אביב-יפו";
  if (name === "נצרת עילית" || name === "נוף הגליל") return "נוף הגליל";
  if (name.startsWith("מודיעין")) return "מודיעין";
  return name;
}
