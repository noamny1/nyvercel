export function landscapeOfDay(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0);
  const day = Math.floor((date.getTime() - start.getTime()) / 86400000);
  return LANDSCAPES[day % LANDSCAPES.length];
}
